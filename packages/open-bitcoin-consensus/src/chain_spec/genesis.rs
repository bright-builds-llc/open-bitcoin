pub(super) fn header(chain: CanonicalChain) -> BlockHeader {
    let (time, nonce, bits) = match chain {
        CanonicalChain::Mainnet => (1_231_006_505, 2_083_236_893, 0x1d00_ffff),
        CanonicalChain::Testnet3 => (1_296_688_602, 414_098_458, 0x1d00_ffff),
        CanonicalChain::Signet => (1_598_918_400, 52_613_770, 0x1e03_77ae),
        CanonicalChain::Regtest => (1_296_688_602, 2, 0x207f_ffff),
    };
    BlockHeader {
        version: 1,
        previous_block_hash: BlockHash::from_byte_array([0; 32]),
        merkle_root: MerkleRoot::from_byte_array(MERKLE_ROOT),
        time,
        bits,
        nonce,
    }
}

pub(super) fn block(chain: CanonicalChain) -> Block {
    Block {
        header: header(chain),
        transactions: vec![coinbase()],
    }
}

// These closed source constants satisfy the domain constructors' bounds:
// 77/67 script bytes < 10,000 and 50 BTC <= MAX_MONEY. No candidate input enters here.
#[expect(
    clippy::expect_used,
    reason = "pinned genesis constants satisfy domain bounds"
)]
fn coinbase() -> Transaction {
    let mut script_sig = vec![0x04, 0xff, 0xff, 0x00, 0x1d, 0x01, 0x04, 0x45];
    script_sig.extend_from_slice(
        b"The Times 03/Jan/2009 Chancellor on brink of second bailout for banks",
    );
    Transaction {
        version: 1,
        inputs: vec![TransactionInput {
            previous_output: OutPoint::null(),
            script_sig: ScriptBuf::from_bytes(script_sig).expect("pinned 77-byte coinbase script"),
            sequence: TransactionInput::SEQUENCE_FINAL,
            witness: ScriptWitness::default(),
        }],
        outputs: vec![TransactionOutput {
            value: Amount::from_sats(5_000_000_000).expect("pinned 50 BTC reward"),
            script_pubkey: ScriptBuf::from_bytes(OUTPUT_SCRIPT.to_vec())
                .expect("pinned 67-byte output script"),
        }],
        lock_time: 0,
    }
}
